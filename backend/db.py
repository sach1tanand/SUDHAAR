import contextlib, hashlib, json, sqlite3, threading
from datetime import datetime, timezone
from .config import DB_PATH, DATABASE_URL

if DATABASE_URL:
    import psycopg
    from psycopg.rows import dict_row

_lock = threading.RLock()

def now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

def conn():
    if DATABASE_URL:
        return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
    c = sqlite3.connect(DB_PATH, check_same_thread=False, timeout=30)
    c.row_factory = sqlite3.Row
    c.execute("PRAGMA foreign_keys=ON")
    return c

def _params(sql: str) -> str:
    """Translate DB-API qmark placeholders to psycopg placeholders, ignoring quoted text."""
    out, quote, i = [], None, 0
    while i < len(sql):
        ch = sql[i]
        if quote:
            out.append(ch)
            if ch == quote:
                if i + 1 < len(sql) and sql[i + 1] == quote:
                    out.append(sql[i + 1]); i += 1
                else: quote = None
        elif ch in ("'", '"'):
            quote = ch; out.append(ch)
        elif ch == "?": out.append("%s")
        else: out.append(ch)
        i += 1
    return "".join(out)

def _pg_schema():
    schema = SCHEMA.replace("id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    with conn() as c:
        for statement in schema.split(";"):
            if statement.strip(): c.execute(statement)
        c.execute("""CREATE OR REPLACE FUNCTION sudhaar_audit_append_only() RETURNS trigger AS $$
        BEGIN RAISE EXCEPTION 'audit log is append-only'; END; $$ LANGUAGE plpgsql""")
        c.execute("DROP TRIGGER IF EXISTS audit_no_update ON audit")
        c.execute("CREATE TRIGGER audit_no_update BEFORE UPDATE OR DELETE ON audit FOR EACH ROW EXECUTE FUNCTION sudhaar_audit_append_only()")

